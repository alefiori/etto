#!/usr/bin/env node
/**
 * Pin the Android WebView text zoom at 100%.
 *
 * Android WebView multiplies all text by the system font-size (accessibility)
 * setting, so a larger system font inflates the app's text and overflows its
 * fixed chrome — the top bar, bottom nav, rings and cards all break. It only
 * happens on Android: iOS WKWebView ignores system scaling entirely, which is
 * the behaviour this matches. The CSS opt-out (`text-size-adjust: 100%` in
 * index.css) is the first line of defence, but recent WebView no longer lets a
 * page disable the accessibility scale that way, so this pins it natively with
 * `setTextZoom(100)`.
 *
 * `android/` is gitignored and regenerated by `npx cap add android` on every
 * build, so there is no checked-in MainActivity to edit. This rewrites the
 * generated one after `cap sync`, from a canonical template keyed on the package
 * name it reads back — the same regenerate-then-patch shape as verify-ipad.mjs.
 * MainActivity is Capacitor's empty default here (no custom plugin registration
 * needs it), so replacing it wholesale is safe.
 *
 * Run after `npx cap sync android`; a no-op with a clear message when android/
 * is absent (a macOS/iOS-only run, say), so it can sit unconditionally in the
 * build script and never fail a build.
 */

import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const ANDROID_SRC = 'android/app/src/main'

/** Java MainActivity that caps the WebView text zoom. */
export function javaSource(pkg) {
  return `package ${pkg};

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onStart() {
        super.onStart();
        // Cap the WebView text zoom so the system font-size (accessibility)
        // setting can't inflate text and break the fixed layout. iOS WKWebView
        // already ignores system scaling; this matches it. android/ is
        // regenerated each build, so this is applied by
        // scripts/patch-android-webview.mjs after \`cap sync\`.
        getBridge().getWebView().getSettings().setTextZoom(100);
    }
}
`
}

/** Kotlin equivalent, for Capacitor templates that scaffold MainActivity.kt. */
export function kotlinSource(pkg) {
  return `package ${pkg}

import com.getcapacitor.BridgeActivity

class MainActivity : BridgeActivity() {
    override fun onStart() {
        super.onStart()
        // See javaSource in scripts/patch-android-webview.mjs for the rationale.
        bridge.webView.settings.textZoom = 100
    }
}
`
}

/** The declared package, or null when the file has no package line. */
export function packageOf(source) {
  const m = source.match(/package\s+([\w.]+)/)
  return m ? m[1] : null
}

/** The MainActivity.{java,kt} under `dir`, searched recursively, or null. */
export function findMainActivity(dir) {
  if (!existsSync(dir)) return null
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) {
      const found = findMainActivity(p)
      if (found) return found
    } else if (entry === 'MainActivity.java' || entry === 'MainActivity.kt') {
      return p
    }
  }
  return null
}

// Only run when executed directly, so the helpers stay importable from the test.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const file =
    findMainActivity(join(ANDROID_SRC, 'java')) || findMainActivity(join(ANDROID_SRC, 'kotlin'))

  if (!file) {
    console.log(
      'patch-android-webview: no android/ MainActivity found, skipping (run `npx cap sync android` first).',
    )
    process.exit(0)
  }

  const original = readFileSync(file, 'utf8')
  if (/setTextZoom|textZoom/.test(original)) {
    console.log('patch-android-webview: WebView text zoom already pinned, nothing to do.')
    process.exit(0)
  }

  const pkg = packageOf(original)
  if (!pkg) {
    console.warn(`patch-android-webview: could not read a package from ${file}; left unchanged.`)
    process.exit(0)
  }

  writeFileSync(file, file.endsWith('.kt') ? kotlinSource(pkg) : javaSource(pkg))
  console.log(`patch-android-webview: pinned WebView textZoom=100 in ${file}`)
}
