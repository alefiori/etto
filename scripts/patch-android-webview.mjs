#!/usr/bin/env node
/**
 * Bound the Android WebView text zoom — without refusing it.
 *
 * This script used to pin the zoom at 100%, which meant the app ignored the
 * system font-size setting outright. That setting is the one accessibility
 * control a low-vision reader is most likely to have already turned on, and
 * ignoring it is a straight failure of WCAG 1.4.4 (Resize Text). It was done
 * because a larger system font overflowed chrome built out of fixed pixel
 * heights — a real problem, solved in the wrong place.
 *
 * The layout absorbs the scale now: the type scale is in rem (src/index.css)
 * and the chrome reserves its measured height rather than a constant
 * (src/hooks/useChromeMetrics.ts). So the zoom is let through, clamped to the
 * 200% the app is built and tested to hold — which is also the figure WCAG
 * asks for. Android's own settings top out at 200% on stock; the clamp is
 * insurance against OEM skins that go further, where the app would otherwise
 * reflow to two words a line.
 *
 * iOS is handled entirely in JS: WKWebView ignores Dynamic Type, so the scale
 * is measured off an `-apple-system-body` probe and applied to the root font
 * size. See src/lib/textScale.ts.
 *
 * `android/` is gitignored and regenerated by `npx cap add android` on every
 * build, so there is no checked-in MainActivity to edit. This rewrites the
 * generated one after `cap sync`, from a canonical template keyed on the package
 * name it reads back — the same regenerate-then-patch shape as verify-ipad.mjs.
 * MainActivity is Capacitor's empty default here (no custom plugin registration
 * needs it), so replacing it wholesale is safe.
 *
 * Run after `npx cap sync android`; a no-op with a clear message when android/
 * is absent (a macOS/iOS-only run, say), so it can sit unconditionally in the
 * build script and never fail a build.
 */

import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const ANDROID_SRC = 'android/app/src/main'

/**
 * The largest system font scale the layout is built to hold, as a percentage.
 *
 * Kept in step with MAX_TEXT_SCALE in src/lib/textScale.ts, which bounds the
 * same thing on iOS. Both are 200% because that is what WCAG 1.4.4 requires.
 */
export const MAX_TEXT_ZOOM = 200

/** Java MainActivity that clamps, rather than pins, the WebView text zoom. */
export function javaSource(pkg) {
  return `package ${pkg};

import android.webkit.WebSettings;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onStart() {
        super.onStart();
        // Honour the system font-size (accessibility) setting, up to the
        // ${MAX_TEXT_ZOOM}% the layout is built to absorb. This used to pin the zoom at
        // 100%, which ignored the setting entirely. android/ is regenerated
        // each build, so this is applied by
        // scripts/patch-android-webview.mjs after \`cap sync\`.
        WebSettings settings = getBridge().getWebView().getSettings();
        settings.setTextZoom(Math.min(settings.getTextZoom(), ${MAX_TEXT_ZOOM}));
    }
}
`
}

/** Kotlin equivalent, for Capacitor templates that scaffold MainActivity.kt. */
export function kotlinSource(pkg) {
  return `package ${pkg}

import com.getcapacitor.BridgeActivity

class MainActivity : BridgeActivity() {
    override fun onStart() {
        super.onStart()
        // See javaSource in scripts/patch-android-webview.mjs for the rationale.
        val settings = bridge.webView.settings
        settings.textZoom = minOf(settings.textZoom, ${MAX_TEXT_ZOOM})
    }
}
`
}

/** The declared package, or null when the file has no package line. */
export function packageOf(source) {
  const m = source.match(/package\s+([\w.]+)/)
  return m ? m[1] : null
}

/** The MainActivity.{java,kt} under `dir`, searched recursively, or null. */
export function findMainActivity(dir) {
  if (!existsSync(dir)) return null
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) {
      const found = findMainActivity(p)
      if (found) return found
    } else if (entry === 'MainActivity.java' || entry === 'MainActivity.kt') {
      return p
    }
  }
  return null
}

// Only run when executed directly, so the helpers stay importable from the test.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const file =
    findMainActivity(join(ANDROID_SRC, 'java')) || findMainActivity(join(ANDROID_SRC, 'kotlin'))

  if (!file) {
    console.log(
      'patch-android-webview: no android/ MainActivity found, skipping (run `npx cap sync android` first).',
    )
    process.exit(0)
  }

  const original = readFileSync(file, 'utf8')
  // Matches the clamp this script writes, not the bare `setTextZoom` an older
  // build left behind — a MainActivity still carrying the 100% pin has to be
  // rewritten, not skipped.
  if (new RegExp(`${MAX_TEXT_ZOOM}\\s*\\)|${MAX_TEXT_ZOOM}\\s*$`, 'm').test(original)) {
    console.log('patch-android-webview: WebView text zoom already clamped, nothing to do.')
    process.exit(0)
  }

  const pkg = packageOf(original)
  if (!pkg) {
    console.warn(`patch-android-webview: could not read a package from ${file}; left unchanged.`)
    process.exit(0)
  }

  writeFileSync(file, file.endsWith('.kt') ? kotlinSource(pkg) : javaSource(pkg))
  console.log(
    `patch-android-webview: clamped WebView textZoom to ${MAX_TEXT_ZOOM}% in ${file}`,
  )
}
