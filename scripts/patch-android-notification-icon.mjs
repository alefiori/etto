#!/usr/bin/env node
/**
 * Write the Android notification small icon the hydration reminders use.
 *
 * Android draws a notification's small icon as a **silhouette**: it keeps the
 * alpha channel and throws the colours away. So the full-colour launcher icon
 * Capacitor falls back to when `smallIcon` is unset arrives in the status bar as
 * a solid grey blob — the single most common way a local-notification feature
 * looks broken while working perfectly. `capacitor.config.ts` therefore names
 * `ic_stat_water_drop`, and this writes it.
 *
 * A **vector** drawable rather than five PNG densities: one file, no raster
 * pipeline, and it scales to whatever the status bar asks for. Notification small
 * icons accept a VectorDrawable from API 21 onward, comfortably below Capacitor
 * 8's floor.
 *
 * The shape is a water drop — the same idea as the app's own water_drop icon —
 * drawn in solid white, which is all a silhouette can carry. `iconColor` in
 * capacitor.config.ts tints the notification's accent separately.
 *
 * `android/` is gitignored and regenerated by `npx cap add android` on every
 * build, so this cannot be a checked-in resource. Run after `npx cap sync
 * android`; a no-op with a clear message when android/ is absent (an iOS-only
 * run, say), so it can sit unconditionally in the build script and never fail a
 * build.
 */

import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DRAWABLE_DIR = 'android/app/src/main/res/drawable'
export const ICON_NAME = 'ic_stat_water_drop'

/**
 * The drawable source.
 *
 * 24dp viewport, which is the size Android composites a small icon at, and a
 * path that stays inside the 22dp keyline the material guidance asks for so the
 * shape is not clipped by the status bar's own padding. Solid `#FFFFFFFF`: a
 * silhouette has no other colour available, and leaving it unset would render
 * black-on-black.
 */
export function notificationIconXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!--
    Generated by scripts/patch-android-notification-icon.mjs — android/ is
    regenerated on every build, so edit the script, not this file.

    Notification small icons are drawn as a silhouette (alpha only), which is why
    this is flat white rather than the brand gradient.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="M12,2.5c-4.1,4.6 -6.5,7.9 -6.5,10.9c0,3.6 2.9,6.1 6.5,6.1s6.5,-2.5 6.5,-6.1C18.5,10.4 16.1,7.1 12,2.5z" />
</vector>
`
}

// Only run when executed directly, so the helpers stay importable from the test.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  if (!existsSync('android/app/src/main/res')) {
    console.log(
      'patch-android-notification-icon: no android/ project found, skipping (run `npx cap sync android` first).',
    )
    process.exit(0)
  }

  mkdirSync(DRAWABLE_DIR, { recursive: true })
  const file = join(DRAWABLE_DIR, `${ICON_NAME}.xml`)
  writeFileSync(file, notificationIconXml())
  console.log(`patch-android-notification-icon: wrote ${file}`)
}
