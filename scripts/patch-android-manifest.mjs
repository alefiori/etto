#!/usr/bin/env node
/**
 * Declare the Android camera permission the barcode scanner needs.
 *
 * BarcodeScanner.tsx opens the camera with plain `getUserMedia` (via @zxing/
 * browser) rather than a Capacitor camera plugin, so nothing in the dependency
 * tree contributes a manifest entry for it. Capacitor's own template declares
 * only INTERNET.
 *
 * That combination fails in a way that looks like the user denied the prompt,
 * because no prompt is ever shown. `BridgeWebChromeClient.onPermissionRequest`
 * sees the WebView's VIDEO_CAPTURE request and launches a runtime request for
 * `android.permission.CAMERA`; Android denies an undeclared permission
 * immediately and silently; Capacitor calls `request.deny()`; `getUserMedia`
 * rejects with NotAllowedError, and the scanner renders `scanner.denied` — "you
 * denied camera access", to a user who was never asked. There is no way out
 * from the app's side, and nothing useful in logcat.
 *
 * This is the Android half of the camera wiring whose iOS half is
 * NSCameraUsageDescription in scripts/patch-ios-project.mjs.
 *
 * The two `uses-feature` lines are not decoration. Declaring the CAMERA
 * permission makes Google Play *imply* `android.hardware.camera` and
 * `android.hardware.camera.autofocus` as **required**, which quietly delists the
 * app for every device without an autofocus rear camera. Scanning is one way to
 * add a food among several, so both are declared optional and the listing stays
 * open; the scanner's existing NotFoundError path already handles a device with
 * no usable camera.
 *
 * `android/` is gitignored and regenerated by `npx cap add android` on every
 * build, so there is no checked-in manifest to edit. Run after `npx cap sync
 * android`; a no-op with a clear message when android/ is absent (an iOS-only
 * run, say), so it can sit unconditionally in the build script and never fail a
 * build.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const MANIFEST = 'android/app/src/main/AndroidManifest.xml'

/** The block inserted ahead of `</manifest>`. */
export const CAMERA_BLOCK = `
    <!--
        Added by scripts/patch-android-manifest.mjs — android/ is regenerated on
        every build, so edit the script, not this file.

        The barcode scanner reaches the camera through getUserMedia, not a
        Capacitor plugin, so no plugin manifest contributes this. Without it
        Android denies the WebView's permission request without prompting and
        the scanner reports a denial the user never made.
    -->
    <uses-permission android:name="android.permission.CAMERA" />

    <!--
        Declaring CAMERA makes Play imply both of these as required, which would
        delist the app on devices without an autofocus rear camera. Scanning is
        optional here — search and manual entry do not need a camera.
    -->
    <uses-feature android:name="android.hardware.camera" android:required="false" />
    <uses-feature android:name="android.hardware.camera.autofocus" android:required="false" />
`

/** True when `manifest` already declares the CAMERA permission. */
export function hasCameraPermission(manifest) {
  return /<uses-permission\s+android:name="android\.permission\.CAMERA"/.test(manifest)
}

/**
 * `manifest` with the camera permission and its feature opt-outs declared.
 *
 * Idempotent, and returns the input untouched when the permission is already
 * there — a future Capacitor template, or a plugin's merged manifest, may cover
 * it. Inserts before the closing `</manifest>`, the one position valid for a
 * top-level element regardless of what else the template holds.
 */
export function withCameraPermission(manifest) {
  if (hasCameraPermission(manifest)) return manifest
  const close = manifest.lastIndexOf('</manifest>')
  if (close === -1) return manifest
  return manifest.slice(0, close) + CAMERA_BLOCK + manifest.slice(close)
}

// Only run when executed directly, so the helpers stay importable from the test.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  if (!existsSync(MANIFEST)) {
    console.log(
      'patch-android-manifest: no android/ project found, skipping (run `npx cap sync android` first).',
    )
    process.exit(0)
  }

  const original = readFileSync(MANIFEST, 'utf8')
  if (hasCameraPermission(original)) {
    console.log('patch-android-manifest: CAMERA permission already declared, nothing to do.')
    process.exit(0)
  }

  const patched = withCameraPermission(original)
  if (patched === original) {
    console.warn(`patch-android-manifest: no </manifest> in ${MANIFEST}; left unchanged.`)
    process.exit(0)
  }

  writeFileSync(MANIFEST, patched)
  console.log(`patch-android-manifest: declared the CAMERA permission in ${MANIFEST}`)
}
